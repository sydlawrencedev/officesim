/** The idle shuffle is the first pair, so the squeal is everything after it */
const FRAMES = [IDLE_STAND, IDLE_STEP, SQUEAL, SQUEAL_UP];

/** How many frames the idle shuffle loops over; the squeal runs on the rest */
export const LLAMA_IDLE_FRAMES = 2;

/** How long each idle frame holds, and each squeal frame: a lazy shuffle, then a quick bleat */
export const LLAMA_IDLE_FRAME_MS = 240;
export const LLAMA_SQUEAL_FRAME_MS = 100;

/** Resolved on first use and then kept, so the palette isn't re-mapped on every frame */
let resolved: SpriteData[] | null = null;

/**
 * One frame as colours, ready for `PixelSprite`. Wraps around, so the caller can just count up
 * through the idle pair (or, offset by {@link LLAMA_IDLE_FRAMES}, through the squeal).
 */
export function llamaFrame(index: number): SpriteData {
  resolved ??= FRAMES.map((frame) => frame.map((row) => [...row].map((key) => PALETTE[key] ?? "")));
  return resolved[((index % resolved.length) + resolved.length) % resolved.length];
}
